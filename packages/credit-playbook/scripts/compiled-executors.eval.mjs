import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdtempSync,rmSync,mkdirSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {rebuildReleasedExecutor} from './build-released-executors.mjs';
import {validateCompiledExecutorRelease} from './compiled-executor-lock.mjs';
const root=resolve(fileURLToPath(new URL('../../..',import.meta.url)));
const require=createRequire(join(root,'apps/document-worker/package.json'));
const {build}=require('esbuild');
const directory=join(root,'packages/credit-playbook/knowledge/releases');
const release=JSON.parse(readFileSync(join(directory,'compiled-executor-lock.json'))).releases[0];
const sha=x=>createHash('sha256').update(x).digest('hex');
const original=()=>JSON.parse(readFileSync(join(directory,release.snapshotHash+'.sources.json')));
async function mutated(mutate,run){
 const temporary=mkdtempSync(join(tmpdir(),'offroad-compiled-negative-'));
 try {
  const snapshot=original();mutate(snapshot);
  const bytes=JSON.stringify(snapshot)+'\n',snapshotHash=sha(bytes);
  writeFileSync(join(temporary,snapshotHash+'.sources.json'),bytes);
  return await run({...release,snapshotHash},temporary);
 }finally{rmSync(temporary,{recursive:true,force:true});}
}
test('compiled artifact reproduces bytes from the snapshot without workspace resolution',async()=>{
 const a=await rebuildReleasedExecutor(release),b=await rebuildReleasedExecutor(release);
 assert.equal(a.artifactHash,release.artifactHash);assert.deepEqual(a.artifact,b.artifact);
 for(const output of Object.values(a.metafile.outputs)){
  assert(output.imports.every(i=>!i.external||i.path==='node:crypto'));
  for(const p of release.parseOnlySources) assert.equal(output.inputs['released:'+p.path]?.bytesInOutput??0,0);
 }
 await validateCompiledExecutorRelease(release,directory);
});
test('compiled artifact denies changed runtime pins and missing dependencies',async()=>{
 await mutated(s=>{const p='packages/financial-model/src/capital-procedure-packet-v2.ts';s.files[p].content+='\n// changed';},(r,d)=>assert.rejects(()=>rebuildReleasedExecutor(r,d),/release_unpinned_first_party_source/));
 await mutated(s=>{delete s.files['packages/financial-model/src/capital-procedure-packet-v2.ts'];},(r,d)=>assert.rejects(()=>rebuildReleasedExecutor(r,d),/release_source_missing/));
});
test('compiled artifact denies changed import edges and broad side-effect overrides',async()=>{
 await mutated(s=>{delete s.edges.entry;},(r,d)=>assert.rejects(()=>rebuildReleasedExecutor(r,d),/release_import_not_recorded/));
 await mutated(s=>{Object.values(s.edges.entry)[0].sideEffects=false;},(r,d)=>assert.rejects(()=>rebuildReleasedExecutor(r,d),/release_side_effect_override_denied/));
});
test('compiled manifest and derived profile cannot be substituted',async()=>{
 await assert.rejects(()=>validateCompiledExecutorRelease({...release,profileFingerprint:'0'.repeat(64)},directory),/compiled_release_profile_mismatch/);
 await mutated(s=>{s.pinned[release.manifestPath]+=' ';},(r,d)=>assert.rejects(()=>validateCompiledExecutorRelease(r,d),/compiled_release_manifest_mismatch/));
});
test('parse-only generated bytes have no runtime effect and runtime retention is denied',async()=>{
 await mutated(s=>{for(const p of release.parseOnlySources){s.files[p.path].content=[...s.files[p.path].content.matchAll(/export const (\w+) =/g)].map(m=>`export const ${m[1]} = {changedExportedValue: true} as const;`).join('\n');s.pinned[p.path]=s.files[p.path].content;}},async(r,d)=>{await assert.rejects(()=>validateCompiledExecutorRelease(r,d),/compiled_release_parse_dependency_mismatch/);assert.equal((await rebuildReleasedExecutor(r,d)).artifactHash,release.artifactHash);});
 await mutated(s=>{for(const edges of Object.values(s.edges))for(const e of Object.values(edges))delete e.sideEffects;},(r,d)=>assert.rejects(()=>rebuildReleasedExecutor({...r,artifactHash:null},d),/release_runtime_source_not_pinned/));
});
test('compiled artifact cannot retain filesystem imports',async()=>{
 await mutated(s=>{
  s.files.entry.content+='\nexport {readFileSync} from "node:fs";';s.edges.entry['node:fs']={external:'node:fs'};
 },(r,d)=>assert.rejects(()=>rebuildReleasedExecutor({...r,artifactHash:null},d),/release_runtime_external_import_denied/));
});
test('published capital artifact reproduces every recorded v4 gold adversarial and consistency case',async()=>{
 const temporary=mkdtempSync(join(tmpdir(),'offroad-compiled-gold-'));
 try{
  const {artifact}=await rebuildReleasedExecutor(release),artifactPath=join(temporary,'capital.cjs');writeFileSync(artifactPath,artifact);
  const outfile=join(temporary,'replay.mjs');
  await build({entryPoints:[join(root,'packages/financial-model/src/capital-procedure-v2-runs.test-support.ts')],outfile,bundle:true,platform:'node',format:'esm',target:'node24',logLevel:'silent',plugins:[{name:'released-calculation',setup(b){
   b.onResolve({filter:/capital-procedure-packet-v2(?:\.ts)?$/},()=>({path:'packet',namespace:'released-packet'}));
   b.onResolve({filter:/capital\.cjs$/},()=>({path:artifactPath,external:true}));
   b.onLoad({filter:/.*/,namespace:'released-packet'},()=>({contents:`import released from ${JSON.stringify(artifactPath)};export const {prepareCapitalProcedurePacketV2,capitalProcedurePacketV2InputSchema,capitalProcedurePacketV2OutputSchema}=released;`,loader:'js'}));
  }}]});
  const {buildCapitalProcedureV2Runs}=await import(pathToFileURL(outfile));
  const observed=buildCapitalProcedureV2Runs('2026.09.21-v4');
  for(const r of observed){
   const record=JSON.parse(readFileSync(join(root,'packages/credit-playbook/knowledge/reviews/runs',r.runId,'run.json')));
   assert.equal(r.result,'pass');assert.equal(r.evidenceFingerprint,record.evidenceFingerprint);assert.deepEqual(r.cases,record.cases);
  }
  assert.equal(observed.reduce((n,r)=>n+r.cases.length,0),26);
 }finally{rmSync(temporary,{recursive:true,force:true});}
});

